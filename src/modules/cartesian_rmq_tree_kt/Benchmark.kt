package com.igorkan.modules.cartesian_rmq_tree_kt

object Benchmark {
    @JvmStatic
    fun main(args: Array<String>) {
        val t0 = System.nanoTime()
        var sink = 0L
        repeat(200) {
            sink += FastPath.quickFold(longArrayOf(1L, 2L, it.toLong()))
        }
        val ns = System.nanoTime() - t0
        println("cartesian_rmq_tree_kt ns=$ns sink=$sink")
    }
}
